function normalizeRole(role) {
  return role === "外籍" ? "外籍技工" : role;
}

function parseCrewText(crewText) {
  const crew = {};
  for (const rawPart of crewText.split("+")) {
    const part = rawPart.replace(/\s+/g, "");
    const roleFirst = part.match(/^([^\d]+)(\d+(?:\.\d+)?)$/);
    const numberFirst = part.match(/^(\d+(?:\.\d+)?)([^\d]+)$/);
    const role = normalizeRole(roleFirst?.[1] ?? numberFirst?.[2] ?? "");
    const count = Number(roleFirst?.[2] ?? numberFirst?.[1]);
    if (!role || !Number.isFinite(count) || count <= 0) {
      throw new Error(`无法解析班组配置：${crewText}`);
    }
    crew[role] = (crew[role] ?? 0) + count;
  }
  return crew;
}

