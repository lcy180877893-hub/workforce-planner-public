const byName = new Map();
let order = 0;
for (const [division, subitems] of groups) {
  for (const [subitem, names] of subitems) {
    for (const name of names) {
      if (byName.has(name)) throw new Error(`房建项目排序中工序重复：${name}`);
      byName.set(name, { division, subitem, hierarchyOrder: ++order });
    }
  }
}

export function hierarchyForName(name) {
  return byName.get(name) ?? null;
}

export const hierarchyEntryCount = byName.size;
